const assert=require('node:assert/strict');
const g=require('../shared/power_architecture.js');
const p={schema_version:'power.system-network/2',sources:[{id:'A',name:'主电源',min:24,max:26,capacity:100},{id:'B',name:'备用电源',min:22,max:25,capacity:100}],units:[],junctions:[{id:'OR',name:'竞争母线',capacity:100}],loads:[{id:'DSP',name:'DSP 与采样',power:5,min:18,max:30}],connections:[{id:'E1',source:{kind:'bus',id:'A',output:1},target:'OR',mode:'diode',vf:.3,enabled:true},{id:'E2',source:{kind:'bus',id:'B',output:1},target:'OR',mode:'diode',vf:.5,enabled:true},{id:'E3',source:{kind:'junction',id:'OR',output:1},target:'DSP',mode:'direct',vf:.3,enabled:true}],layout:{nodes:{}}};
g.autoArrange(p);g.saveLayout(p);
assert.equal(g.layout(p).length,4);
const svg=g.svg(p,{interactive:true});
assert.match(svg,/data-graph-node="load:DSP"/);assert.match(svg,/data-graph-node="junction:OR"/);
assert.match(svg,/data-edge="E1"/);assert.match(svg,/data-edge="E2"/);assert.match(svg,/data-diode-symbol/);
assert.ok(!svg.includes('undefined'));assert.ok(!svg.includes('NaN'));
assert.match(g.connectionError(p,'OR',{kind:'junction',id:'OR',output:1}),/循环/);
assert.match(g.connectionError(p,'OR',{kind:'load',id:'DSP',output:1}),/不存在/);
assert.ok(!g.svg(p).includes('data-node-delete'));
const record=g.removeNode(p,'bus:A');assert.equal(p.connections.length,2);
assert.ok(g.restoreNode(p,record));assert.equal(p.connections.length,3);
assert.equal(g.layout(p).find(n=>n.kind==='load').ports,0);
p.layout.diodes={E1:{x:720,y:360}};
g.saveLayout(p);assert.deepEqual(p.layout.diodes.E1,{x:720,y:360});
assert.match(g.svg(p,{interactive:true}),/data-diode-drag="E1"/);
assert.match(g.svg(p),/translate\(720 360\)/);
const moved=g.removeNode(p,'bus:A');assert.ok(!p.layout.diodes.E1);g.restoreNode(p,moved);assert.deepEqual(p.layout.diodes.E1,{x:720,y:360});
console.log('PASS network graph: independent edges, OR fan-in, named terminal load, delete/undo and clean SVG');
